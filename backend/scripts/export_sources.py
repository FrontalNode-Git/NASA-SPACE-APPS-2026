"""Write docs/SOURCES.txt: the plain-text record of where every statement in VITAL comes from.

The app is a crew tool and shows no citations on screen, so this file is the place to look.
It is generated from data/sources/*.json. Run it from backend/ after every change to those files:

    python scripts/export_sources.py           # rewrite docs/SOURCES.txt
    python scripts/export_sources.py --check   # exit 1 if the file is out of date

Standard library only.
"""
from __future__ import annotations

import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # repo root: backend/scripts/ -> backend/ -> repo
SOURCES = ROOT / "data" / "sources"
OUT = ROOT / "docs" / "SOURCES.txt"
WIDTH = 96


def _load(name: str) -> list[dict]:
    return json.loads((SOURCES / f"{name}.json").read_text(encoding="utf-8"))


def _wrap(label: str, text: str, indent: str = "    ") -> list[str]:
    first = f"{indent}{label}"
    return textwrap.wrap(text, width=WIDTH, initial_indent=first, subsequent_indent=" " * len(first)) or [first]


def _rule(title: str) -> list[str]:
    return ["", title, "-" * len(title)]


def render() -> str:
    facts = _load("facts")
    hazards = _load("hazards")
    risks = _load("risks")
    research = _load("research")
    approved = json.loads((SOURCES / "approved_urls.json").read_text(encoding="utf-8"))

    pages: dict[str, dict] = {}
    for fact in facts:
        page = pages.setdefault(fact["url"], {"title": fact["page_title"], "fetched": fact["fetched_at"], "facts": []})
        page["facts"].append(fact)
        page["fetched"] = max(page["fetched"], fact["fetched_at"])

    lines = [
        "VITAL SOURCES",
        "==============",
        "",
        "Every fact, number, name and health description in VITAL comes from the pages below.",
        "The app does not show citations on screen. This file is the record.",
        "",
        "Generated by backend/scripts/export_sources.py from data/sources/*.json. Do not edit by hand.",
        f"{len(facts)} facts from {len(pages)} pages. {len(hazards)} hazards, {len(risks)} risks, {len(research)} studies.",
    ]

    lines += _rule("1. SOURCE PAGES")
    for url in approved["seeds"]:
        page = pages.get(url)
        lines.append(f"  {page['title'] if page else '(no facts taken yet)'}")
        lines.append(f"    {url}")
        if page:
            lines.append(f"    fetched {page['fetched']} · {len(page['facts'])} facts")
    lines.append("")
    lines.append("  Only these pages, and NASA / CSA pages linked directly from them, may be used.")

    lines += _rule("2. FACTS, BY SOURCE PAGE")
    for url, page in pages.items():
        lines += ["", f"  {page['title']}", f"  {url}", ""]
        for fact in page["facts"]:
            lines.append(f"  [{fact['id']}]")
            lines += _wrap("Shown as: ", fact["text"])
            lines += _wrap("Quote:    ", f"\"{fact['quote']}\"")
            used = [f"{kind}: {', '.join(ids)}" for kind, ids in fact.get("links", {}).items() if ids]
            if used:
                lines += _wrap("Used for: ", "; ".join(used))
            lines.append("")

    lines += _rule("3. HAZARD PAGES (NASA)")
    for hazard in hazards:
        lines += [f"  {hazard['name']}", f"    {hazard['url']}"]

    lines += _rule("4. RISK PAGES (NASA)")
    for risk in risks:
        lines += [f"  {risk['name']}", f"    {risk['url']}"]

    lines += _rule("5. STUDY PAGES (NASA)")
    for study in research:
        lines += [f"  {study['name']}", f"    {study['url']}"]

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/SOURCES.txt is out of date. Run (in backend/): python scripts/export_sources.py")
            return 1
        print("docs/SOURCES.txt is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
